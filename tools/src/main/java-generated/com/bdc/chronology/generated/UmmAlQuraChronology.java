  private static int idx(int year, int month) {
    return (year - MIN_YEAR) * 12 + (month - 1);
  }

  public UmmAlQuraChronology() {}

  @Override
  public String getChronologyId() {
    return ID;
  }

  @Override
  public boolean isLeapYear(int year) {
    if (year < MIN_YEAR || year > MAX_YEAR) return false;
    int total = 0;
    int base = (year - MIN_YEAR) * 12;
    for (int m = 0; m < 12; m++) {
      total += MONTH_LEN[base + m];
    }
    return total == 355;
  }

  @Override
  public int getDaysInMonth(int year, int month) {
    if (month < 1 || month > 12) {
      throw new IllegalArgumentException("Invalid month: " + month);
    }
    if (year < MIN_YEAR || year > MAX_YEAR) {
      throw new IllegalArgumentException(
          "Year " + year + " outside supported range [" + MIN_YEAR + ", " + MAX_YEAR + "]");
    }
    return MONTH_LEN[idx(year, month)];
  }

  @Override
  public boolean isValidDate(int year, int month, int day) {
    if (year < MIN_YEAR || year > MAX_YEAR) return false;
    if (month < 1 || month > 12) return false;
    if (day < 1) return false;
    return day <= getDaysInMonth(year, month);
  }

  @Override
  public long toJdn(int year, int month, int day) {
    if (!isValidDate(year, month, day)) {
      throw new IllegalArgumentException("Invalid date: " + year + "-" + month + "-" + day);
    }
    return MONTH_JDN[idx(year, month)] + day - 1;
  }

  @Override
  public ChronologyDate fromJdn(long jdn) {
    if (jdn < MONTH_JDN[0]) {
      throw new IllegalArgumentException("JDN " + jdn + " is before supported range");
    }
    // Binary search for year
    int year = MIN_YEAR;
    for (int y = MIN_YEAR; y <= MAX_YEAR; y++) {
      if (MONTH_JDN[(y - MIN_YEAR) * 12] > jdn) break;
      year = y;
    }
    // Find month
    int base = (year - MIN_YEAR) * 12;
    for (int m = 0; m < 12; m++) {
      long monthStart = MONTH_JDN[base + m];
      int monthLen = MONTH_LEN[base + m];
      if (jdn >= monthStart && jdn < monthStart + monthLen) {
        int day = (int) (jdn - monthStart) + 1;
        return new ChronologyDate(ID, year, m + 1, day);
      }
    }
    throw new IllegalArgumentException("JDN " + jdn + " outside supported range");
  }
