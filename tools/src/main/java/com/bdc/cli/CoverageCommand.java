package com.bdc.cli;

import com.bdc.artifact.ReleaseHistoryStore;
import com.bdc.model.EventStatus;
import com.bdc.stream.DateStream;
import com.bdc.trust.DayAssessment;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.Callable;
import picocli.CommandLine.Command;
import picocli.CommandLine.Option;

/**
 * The coverage assessment snapshot: for every blessed calendar, how many covered dates answer the
 * business-day question and the full session question at each confidence, computed with the same
 * {@link DateStream#assessment} the query API uses.
 */
@Command(
    name = "coverage",
    description = "Coverage assessment snapshot: confidence counts per blessed calendar")
public class CoverageCommand implements Callable<Integer> {

  @Option(
      names = {"--format"},
      description = "Output format: markdown or json",
      defaultValue = "markdown")
  private String format;

  @Option(
      names = {"--blessed-dir"},
      description = "Blessed artifacts directory",
      defaultValue = "blessed")
  private Path blessedDir;

  @Option(
      names = {"--release-history-dir"},
      description = "Release history directory",
      defaultValue = "release-history")
  private Path releaseHistoryDir;

  @Option(
      names = {"--out"},
      description = "Write the report here instead of stdout")
  private Path out;

  private final ObjectMapper mapper = new ObjectMapper().enable(SerializationFeature.INDENT_OUTPUT);

  @Override
  public Integer call() {
    try {
      Path manifestPath = blessedDir.resolve("manifest.json");
      if (!Files.exists(manifestPath)) {
        System.err.println("Coverage failed: manifest not found: " + manifestPath);
        return 1;
      }
      JsonNode manifest = mapper.readTree(manifestPath.toFile());
      String version = manifest.path("release_version").path("semantic").asText("unknown");
      List<String> ids = new ArrayList<>();
      manifest.path("calendars").fieldNames().forEachRemaining(ids::add);
      ids.sort(String::compareTo);
      ReleaseHistoryStore store = new ReleaseHistoryStore(releaseHistoryDir, blessedDir);

      List<Map<String, Object>> rows = new ArrayList<>();
      for (String id : ids) {
        var snapshot = store.resolve(id, "latest");
        if (snapshot.isEmpty()) continue;
        rows.add(row(id, store.stream(snapshot.get())));
      }
      String rendered =
          format.equalsIgnoreCase("json")
              ? mapper.writeValueAsString(Map.of("data_version", version, "calendars", rows))
              : markdown(version, rows);
      if (out != null) {
        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.writeString(out, rendered);
      } else {
        System.out.print(rendered);
      }
      return 0;
    } catch (IOException e) {
      System.err.println("Coverage failed: " + e.getMessage());
      return 1;
    }
  }

  static Map<String, Object> row(String id, DateStream stream) {
    Counts businessDay = new Counts();
    Counts session = new Counts();
    LocalDate start = stream.range().start();
    LocalDate end = stream.range().end();
    for (LocalDate date = start; !date.isAfter(end); date = date.plusDays(1)) {
      DayAssessment assessment = stream.assessment(date);
      businessDay.add(assessment.businessDayConfidence());
      session.add(assessment.effectiveConfidence());
    }
    Map<String, Object> row = new LinkedHashMap<>();
    row.put("id", id);
    row.put("from", start.toString());
    row.put("to", end.toString());
    row.put("days", businessDay.total());
    row.put("business_day", businessDay.toMap());
    row.put("session", session.toMap());
    return row;
  }

  @SuppressWarnings("unchecked")
  static String markdown(String version, List<Map<String, Object>> rows) {
    StringBuilder md = new StringBuilder();
    md.append("# Coverage assessment snapshot\n\n");
    md.append("Generated by `tools coverage` from the blessed data ")
        .append(version)
        .append(". Counts include every covered civil date and use the same effective\n")
        .append("confidence as the query API (`assessment(date)`), so this table is a faithful\n")
        .append("summary of what the published data will and will not answer.\n\n");
    md.append("Two questions are counted separately, because they depend on different evidence\n")
        .append("scopes (see `spec/SPEC.md`, *Questions and the scopes they need*):\n\n");
    md.append("- **Business day** — `is_business_day`, navigation, counts and financial date\n")
        .append(
            "  operations. Needs scheduled closures and unscheduled exceptions. UNKNOWN dates\n")
        .append(
            "  raise `UnresolvedDateException` / `UnresolvedDateError` from these operations.\n");
    md.append("- **Session** — `close_time`, `is_early_close` and `status`. Additionally needs\n")
        .append("  early-close evidence, so a calendar with an early-close gap can be fully\n")
        .append("  answerable for business days while its close times stay UNKNOWN.\n\n");
    md.append("PROJECTED dates remain usable with their stated uncertainty. Sources and scope\n")
        .append(
            "intervals are linked in each calendar's compiled metadata; the canonical evidence\n")
        .append("registers are under `sources/`.\n\n");
    md.append(
        "| Calendar | Covered interval | Days | Business day: CONFIRMED | PROJECTED | UNKNOWN |"
            + " Session: CONFIRMED | PROJECTED | UNKNOWN |\n");
    md.append("|---|---|---:|---:|---:|---:|---:|---:|---:|\n");
    for (Map<String, Object> row : rows) {
      Map<String, Object> bd = (Map<String, Object>) row.get("business_day");
      Map<String, Object> se = (Map<String, Object>) row.get("session");
      md.append("| [")
          .append(row.get("id"))
          .append("](../../blessed/")
          .append(row.get("id"))
          .append("/metadata.json) | ")
          .append(row.get("from"))
          .append(" – ")
          .append(row.get("to"))
          .append(" | ")
          .append(row.get("days"))
          .append(" | ")
          .append(bd.get("CONFIRMED"))
          .append(" | ")
          .append(bd.get("PROJECTED"))
          .append(" | ")
          .append(bd.get("UNKNOWN"))
          .append(" | ")
          .append(se.get("CONFIRMED"))
          .append(" | ")
          .append(se.get("PROJECTED"))
          .append(" | ")
          .append(se.get("UNKNOWN"))
          .append(" |\n");
    }
    return md.toString();
  }

  private static final class Counts {
    private long confirmed;
    private long projected;
    private long unknown;

    void add(EventStatus status) {
      switch (status) {
        case CONFIRMED -> confirmed++;
        case PROJECTED -> projected++;
        default -> unknown++;
      }
    }

    long total() {
      return confirmed + projected + unknown;
    }

    Map<String, Object> toMap() {
      Map<String, Object> map = new LinkedHashMap<>();
      map.put("CONFIRMED", confirmed);
      map.put("PROJECTED", projected);
      map.put("UNKNOWN", unknown);
      return map;
    }
  }
}
